namespace wf {
namespace {
const char* kWasiRunner = R"JS(// Generated by WasmForge: runs a WASI command module with Node's built-in WASI.
// The module can only touch the current directory (the build output directory).
const { WASI } = require('node:wasi');
const fs = require('fs');
(async () => {
  const file = process.argv[2];
  const wasi = new WASI({ version: 'preview1', args: [file, ...process.argv.slice(3)], env: {}, preopens: { '.': '.' } });
  const mod = await WebAssembly.compile(fs.readFileSync(file));
  const inst = await WebAssembly.instantiate(mod, wasi.getImportObject());
  const code = wasi.start(inst);
  process.exitCode = code === undefined ? 0 : code;
})().catch((e) => { console.error(String((e && e.stack) || e)); process.exit(1); });
)JS";
}  // namespace

RunResult runBuilt(const RunOptions& o) {
  RunResult R;
  std::error_code ec;
  const fs::path js = o.outDir / fromUtf8(o.name + ".js"), wasm = o.outDir / fromUtf8(o.name + ".wasm");
  std::vector<std::string> argv;
  if (fs::exists(js, ec)) {
    R.found = true;
    const auto node = findInPath("node");
    if (!node) {
      R.note = "Node.js was not found in PATH; it is needed to run Emscripten output outside a browser (install it, or use `wasmfrg serve`)";
      return R;
    }
    R.runtime = "node";
    argv = {pathStr(*node), pathStr(js)};
  } else if (fs::exists(wasm, ec)) {
    R.found = true;
    if (auto wt = findInPath("wasmtime")) { R.runtime = "wasmtime"; argv = {pathStr(*wt), pathStr(wasm)}; }
    else if (auto wm = findInPath("wasmer")) { R.runtime = "wasmer"; argv = {pathStr(*wm), "run", pathStr(wasm)}; }
    else if (auto node = findInPath("node")) {
      const fs::path script = o.genDir / "run-wasi.js";
      if (!writeFileAtomic(script, kWasiRunner)) { R.note = "cannot write " + pathStr(script); return R; }
      R.runtime = "node:wasi";
      argv = {pathStr(*node), "--no-warnings", pathStr(script), pathStr(wasm)};
    } else {
      R.note = "no WASI runtime found (wasmtime, wasmer, or Node.js)";
      return R;
    }
  } else {
    R.note = "nothing to run: " + pathStr(js) + " / .wasm not found (build first)";
    return R;
  }
  for (const auto& a : o.args) argv.push_back(a);
  const ProcessResult pr = runProcess(argv, o.outDir, true, o.timeoutSec);
  R.started = pr.started;
  R.timedOut = pr.timedOut;
  R.exitCode = pr.exitCode;
  R.seconds = pr.seconds;
  R.output = pr.started ? pr.output : pr.error;
  return R;
}
}  // namespace wf
